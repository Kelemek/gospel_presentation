#!/usr/bin/env bash
# Shared paths for verify-gospel-presentation (sourced, not executed).

set -euo pipefail

VERIFY_SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERIFY_REPO_ROOT="$(cd "$VERIFY_SKILL_DIR/../../../.." && pwd)"
VERIFY_APP_DIR="$VERIFY_REPO_ROOT/gospel-admin"
VERIFY_EVIDENCE_ROOT="$VERIFY_SKILL_DIR/../evidence/runs"
VERIFY_STATE_DIR="$VERIFY_SKILL_DIR/../.state"
VERIFY_TMUX_SESSION="gospel-verify-dev"
VERIFY_BASE_URL="${VERIFY_BASE_URL:-http://127.0.0.1:3000}"
VERIFY_DEV_PORT="${VERIFY_DEV_PORT:-3000}"

if [[ -z "${VERIFY_RUN_ID:-}" ]]; then
  VERIFY_RUN_ID="$(date -u +%Y%m%dT%H%M%SZ)-$$"
fi

VERIFY_RUN_EVIDENCE="$VERIFY_EVIDENCE_ROOT/$VERIFY_RUN_ID"
mkdir -p "$VERIFY_RUN_EVIDENCE" "$VERIFY_STATE_DIR"

verify_nvm_use() {
  # shellcheck source=/dev/null
  if [[ -s "$HOME/.nvm/nvm.sh" ]]; then
    source "$HOME/.nvm/nvm.sh"
    (cd "$VERIFY_APP_DIR" && nvm use)
  fi
}

verify_materialize_env_local() {
  local env_file="$VERIFY_APP_DIR/.env.local"
  if [[ -f "$env_file" ]]; then
    return 0
  fi
  if [[ -z "${NEXT_PUBLIC_SUPABASE_URL:-}" ]]; then
    echo "verify-gp: no .env.local and NEXT_PUBLIC_SUPABASE_URL unset; profile routes may fail"
    return 0
  fi
  {
    echo "# Generated by verify-gp for local dev (gitignored). Do not commit."
    [[ -n "${NEXT_PUBLIC_SUPABASE_URL:-}" ]] && echo "NEXT_PUBLIC_SUPABASE_URL=$NEXT_PUBLIC_SUPABASE_URL"
    [[ -n "${NEXT_PUBLIC_SUPABASE_ANON_KEY:-}" ]] && echo "NEXT_PUBLIC_SUPABASE_ANON_KEY=$NEXT_PUBLIC_SUPABASE_ANON_KEY"
    [[ -n "${SUPABASE_SERVICE_KEY:-}" ]] && echo "SUPABASE_SERVICE_KEY=$SUPABASE_SERVICE_KEY"
    [[ -n "${SUPABASE_SERVICE_ROLE_KEY:-}" && -z "${SUPABASE_SERVICE_KEY:-}" ]] && echo "SUPABASE_SERVICE_KEY=$SUPABASE_SERVICE_ROLE_KEY"
    [[ -n "${ESV_API_TOKEN:-}" ]] && echo "ESV_API_TOKEN=$ESV_API_TOKEN"
  } >"$env_file"
  echo "verify-gp: wrote $env_file from environment"
}

verify_ensure_playwright() {
  if [[ ! -d "$VERIFY_SKILL_DIR/node_modules/playwright" ]]; then
    verify_nvm_use
    (cd "$VERIFY_SKILL_DIR" && npm install --omit=dev)
    (cd "$VERIFY_SKILL_DIR" && npx playwright install chromium)
  fi
}

verify_record_doctor() {
  {
    echo "run_id=$VERIFY_RUN_ID"
    echo "base_url=$VERIFY_BASE_URL"
    echo "tmux_session=$VERIFY_TMUX_SESSION"
    date -u +"%Y-%m-%dT%H:%M:%SZ"
  } >"$VERIFY_RUN_EVIDENCE/doctor-meta.txt"
}
